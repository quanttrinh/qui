/// <reference types="node" />
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

import { type Config } from "../config";
import { componentDeclarationsFromSource } from "./component-tags";

/**
 * Collects the tags of components marked with `@undefinedContent` in their
 * class documentation. The marker keeps the metadata beside the component
 * instead of duplicating its tag in a build-time list.
 */
export async function undefinedContentTagsFromSource(config: Config): Promise<string[]> {
  const tags = new Set<string>();
  let files: string[];

  try {
    files = await readdir(config.source.components, {
      encoding: "utf8",
      recursive: true,
    });
  } catch {
    return [];
  }

  for (const file of files) {
    if (!file.endsWith(".tsx")) {
      continue;
    }
    const path = join(config.source.components, file);
    const source = await readFile(path, "utf8");
    if (!source.includes("@undefinedContent")) {
      continue;
    }

    for (const declaration of componentDeclarationsFromSource(source)) {
      if (declaration.undefinedContent) {
        tags.add(declaration.tag);
      }
    }
  }

  return [...tags].toSorted();
}

/** Renders the static module imported by the Panda config. */
function undefinedContentTagsModule(tags: readonly string[]): string {
  const entries = tags.map((tag) => `  ${JSON.stringify(tag)},`).join("\n");
  return [
    "// Generated by the Stencil styles plugin. Do not edit.",
    "export const UNDEFINED_CONTENT_TAGS = [",
    entries,
    "] as const;",
    "",
  ].join("\n");
}

/** Writes the tag module used by the Panda config. */
export async function writeUndefinedContentTags(
  config: Config,
  tags?: readonly string[],
): Promise<void> {
  const resolvedTags = tags ?? (await undefinedContentTagsFromSource(config));
  const contents = undefinedContentTagsModule(resolvedTags);
  const file = config.file.undefinedContentTags;

  try {
    if ((await readFile(file, "utf8")) === contents) {
      return;
    }
  } catch {
    // The module does not exist yet.
  }

  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, contents);
}
